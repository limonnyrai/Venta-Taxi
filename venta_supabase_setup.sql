create table if not exists public.driver_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  email text,
  car_info text not null,
  city text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.driver_applications enable row level security;
revoke all on table public.driver_applications from anon, authenticated;
grant select, insert, update on table public.driver_applications to authenticated;

drop policy if exists "Users can read own driver application" on public.driver_applications;
drop policy if exists "Users can create own driver application" on public.driver_applications;
drop policy if exists "Users can update own driver application" on public.driver_applications;
drop policy if exists "Admin can read all driver applications" on public.driver_applications;
drop policy if exists "Admin can update driver applications" on public.driver_applications;

create policy "Users can read own driver application"
on public.driver_applications for select to authenticated
using ((select auth.uid()) = user_id);

create policy "Users can create own driver application"
on public.driver_applications for insert to authenticated
with check ((select auth.uid()) = user_id);

create policy "Users can update own driver application"
on public.driver_applications for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "Admin can read all driver applications"
on public.driver_applications for select to authenticated
using (lower(coalesce((select auth.jwt() ->> 'email'),'')) = lower('jony.oficcial@mail.ru'));

create policy "Admin can update driver applications"
on public.driver_applications for update to authenticated
using (lower(coalesce((select auth.jwt() ->> 'email'),'')) = lower('jony.oficcial@mail.ru'))
with check (true);

-- Сохранённые адреса пользователя
