-- Разрешённый список профилей без номера телефона, для разделения счёта
create or replace function public.venta_list_profiles()
returns table(id uuid, email text, first_name text, last_name text)
language sql
security definer
set search_path = public
as $$
  select vp.id, vp.email, vp.first_name, vp.last_name
  from public.venta_profiles vp
  where auth.uid() is not null
  order by coalesce(vp.first_name,''), coalesce(vp.last_name,'');
$$;

revoke all on function public.venta_list_profiles() from public;
grant execute on function public.venta_list_profiles() to authenticated;
